// Plain-language guides. Written for someone who knows building, not phones: short sentences, no technical words.

// The steps shown before handing the picture over to another app. `save` platforms have no share target, so the picture is saved instead.
export function uploadSteps(platform,fmt){
  const story=fmt==="story";
  switch(platform){
    case "instagram":return [
      {t:"Изберете Instagram",d:"От списъка, който ще се отвори, изберете Instagram."+(story?" Когато пита, изберете „Сторис“.":" Когато пита, изберете „Пост“.")},
      ...(story?[{t:"Текст не е нужен",d:"Всичко нужно вече е на картинката."}]:[{t:"Поставете текста",d:"Натиснете полето за текст. Над клавиатурата ще се покаже вашият текст — натиснете го. Ако не се показва, задръжте пръст в полето и изберете „Постави“."}]),
      {t:"Публикувайте",d:"Натиснете „Споделяне“."}];
    case "tiktok":return [
      {t:"Изберете TikTok",d:"От списъка, който ще се отвори, изберете TikTok."},
      {t:"Поставете текста",d:"Натиснете полето за описание. Над клавиатурата ще се покаже вашият текст — натиснете го."},
      {t:"Публикувайте",d:"Натиснете „Публикуване“."}];
    case "youtube":return [
      {t:"Картинката се запазва",d:"Запазваме корицата в телефона, а текстът се копира."},
      {t:"Качете клипа в YouTube",d:"Отворете YouTube, натиснете „+“ и изберете клипа."},
      {t:"Сложете корицата и текста",d:"Когато ви питат за „миниатюра“, изберете запазената картинка. В „Описание“ поставете текста."}];
    case "viber":return [
      {t:"Изберете Viber",d:"От списъка, който ще се отвори, изберете Viber и после групата или човека."},
      {t:"Проверете текста",d:"Ако текстът не се появи до картинката, натиснете полето за съобщение и го поставете."},
      {t:"Изпратете",d:"Натиснете стрелката за изпращане."}];
    case "google":return [
      {t:"Картинката се запазва",d:"Запазваме картинката в телефона, а текстът се копира."},
      {t:"Отворете профила на фирмата",d:"В Google Maps натиснете „Вие“ → „Вашият профил на фирмата“ → „Добавяне на актуализация“."},
      {t:"Добавете и публикувайте",d:"Изберете запазената картинка, поставете текста и натиснете „Публикуване“."}];
    case "ads":return [
      {t:"Картинката се запазва",d:"Запазваме картинката в телефона, а текстът се копира."},
      {t:"Започнете обява",d:"Отворете OLX или imot.bg и натиснете „Нова обява“."},
      {t:"Добавете и публикувайте",d:"Добавете запазената картинка, поставете текста в описанието и публикувайте."}];
    default:return [
      {t:"Изберете Facebook",d:"От списъка, който ще се отвори, изберете Facebook."+(story?" Когато пита къде, изберете „Сторис“.":" Когато пита къде, изберете „Новини“.")},
      ...(story?[{t:"Текст не е нужен",d:"Всичко нужно вече е на картинката."}]:[
        {t:"Поставете текста",d:"Във Facebook натиснете полето за текст. Над клавиатурата ще се покаже вашият текст — натиснете го. Ако не се показва, задръжте пръст в полето и изберете „Постави“."},
        {t:"Още снимки (по желание)",d:"Натиснете малката иконка със снимки и добавете още от обекта."}]),
      {t:"Публикувайте",d:"Натиснете „Публикуване“ (или „Сподели“) горе вдясно."}];
  }
}

